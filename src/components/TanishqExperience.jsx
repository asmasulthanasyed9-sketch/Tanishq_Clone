const experiences = [
  { icon: <StoreIcon />, label: 'Visit Our Store', href: '#' },
  { icon: <CalendarIcon />, label: 'Book an Appointment', href: '#' },
  { icon: <PhoneIcon />, label: 'Talk to an Expert', href: '#' },
  { icon: <GoldIcon />, label: 'Digi Gold', href: '#' },
  { icon: <BlogIcon />, label: 'Blogs', href: '#' },
  { icon: <GuideIcon />, label: 'Jewellery Guide', href: '#' },
];

export default function TanishqExperience() {
  const ref = useRef(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const obs = new IntersectionObserver(([e]) => {
      if (e.isIntersecting) { setVisible(true); obs.disconnect(); }
    }, { threshold: 0.1 });
    if (ref.current) obs.observe(ref.current);
    return () => obs.disconnect();
  }, []);

  return (
    <section className="experience-section section-wrapper" ref={ref}>
      <div className="container">
        <div className="section-heading" style={{ opacity: visible ? 1 : 0, transition: 'opacity 0.6s ease' }}>
          <h2>Tanishq Experience</h2>
          <p>Find a Boutique or Book a Consultation</p>
        </div>
        <div className="experience-grid">
          {experiences.map((exp, idx) => (
            <a
              href={exp.href}
              className="exp-card"
              key={idx}
              style={{
                opacity: visible ? 1 : 0,
                transform: visible ? 'translateY(0)' : 'translateY(20px)',
                transition: `opacity 0.5s ease ${idx * 0.08}s, transform 0.5s ease ${idx * 0.08}s`,
              }}
            >
              <div className="exp-icon">{exp.icon}</div>
              <h4>{exp.label}</h4>
            </a>
          ))}
        </div>
      </div>
    </section>
  );
}
